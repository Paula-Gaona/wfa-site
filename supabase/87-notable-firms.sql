-- WFA update: a list of big-name firms (Wall Street, buy side, Big 4, consulting, large companies like the Fortune 500
-- and big private companies such as Chick-fil-A and In-N-Out, and notable Utah employers) for the newsletter's "Opportunities" section. Postings from these firms are
-- picked first (then Utah postings, then the newest). Admins edit the list in Officer tools -> Email -> Newsletter.
-- aliases: other names the firm shows up under in listings ("JPMorgan", "Chase").
-- Run once in Supabase -> SQL Editor. Safe to run again (it only adds firms that aren't on the list yet).

create table if not exists public.notable_firms (
  id uuid primary key default gen_random_uuid(),
  name text not null unique check (char_length(name) between 1 and 120),
  kind text not null,
  aliases text[] not null default '{}'
);
alter table public.notable_firms drop constraint if exists notable_firms_kind_check;
alter table public.notable_firms add constraint notable_firms_kind_check check (kind in ('wall_street', 'buy_side', 'big4', 'consulting', 'big_company', 'utah'));
alter table public.notable_firms enable row level security;
drop policy if exists "officers read notable firms" on public.notable_firms;
create policy "officers read notable firms" on public.notable_firms for select using (is_officer());
drop policy if exists "admins manage notable firms" on public.notable_firms;
create policy "admins manage notable firms" on public.notable_firms for all using (is_admin()) with check (is_admin());
grant select, insert, update, delete on public.notable_firms to authenticated;

